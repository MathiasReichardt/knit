using System.Net;
using System.Net.Http.Json;
using System.Net.Sockets;
using System.Text.Json;
using Knit.Core.Config;
using Knit.WebApi;
using Knit.WebApi.Contracts;

namespace Knit.Cli.Tests;

/// <summary>
/// <c>POST /api/status/report</c>, behind the SPA menu's
/// "Write status report": the same file `knit status report` writes, at the
/// configured path, and never over a hand-written one.
/// </summary>
public class WebApiStatusReportTests : IDisposable
{
    private static readonly JsonSerializerOptions Web = new(JsonSerializerDefaults.Web);

    private readonly string _root = Path.Combine(Path.GetTempPath(), $"knit-reportapi-{Guid.NewGuid():N}");

    public WebApiStatusReportTests()
    {
        Directory.CreateDirectory(Path.Combine(_root, ".knit", "items"));
        File.WriteAllText(Path.Combine(_root, ".knit", ConfigLoader.FileName), "{}");
    }

    public void Dispose()
    {
        try { Directory.Delete(_root, recursive: true); } catch (IOException) { }
    }

    [Fact]
    public async Task Writes_the_page_and_returns_its_repo_relative_path() =>
        await WithApi(async http =>
        {
            var r = await http.PostAsync("/api/status/report", null);
            r.EnsureSuccessStatusCode();
            Assert.Equal(new StatusReportDto("project-status.md", true), await r.Content.ReadFromJsonAsync<StatusReportDto>(Web));
            Assert.StartsWith("<!-- generated by knit status report", await File.ReadAllTextAsync(Path.Combine(_root, "project-status.md")));
        });

    [Fact]
    public async Task Writes_to_the_configured_path() =>
        await WithApi(async http =>
        {
            await File.WriteAllTextAsync(Path.Combine(_root, ".knit", ConfigLoader.FileName), """{"status_report.path":"docs/status.md"}""");
            var r = await http.PostAsync("/api/status/report", null);
            r.EnsureSuccessStatusCode();
            Assert.Equal("docs/status.md", (await r.Content.ReadFromJsonAsync<StatusReportDto>(Web))!.Path);
            Assert.True(File.Exists(Path.Combine(_root, "docs", "status.md")));
        });

    [Fact]
    public async Task A_target_without_the_marker_is_left_unchanged_and_names_the_force_command() =>
        await WithApi(async http =>
        {
            var target = Path.Combine(_root, "project-status.md");
            await File.WriteAllTextAsync(target, "# Ours\n");
            var r = await http.PostAsync("/api/status/report", null);
            Assert.Equal(HttpStatusCode.Conflict, r.StatusCode);
            var problem = await r.Content.ReadFromJsonAsync<JsonElement>(Web);
            Assert.Equal("not_generated", problem.GetProperty("code").GetString());
            Assert.Contains("knit status report --force", problem.GetProperty("detail").GetString());
            Assert.Equal("# Ours\n", await File.ReadAllTextAsync(target));
        });

    [Fact]
    public async Task Get_reports_no_page_then_a_fresh_one_then_a_stale_one() =>
        await WithApi(async http =>
        {
            var none = await http.GetFromJsonAsync<StatusPageDto>("/api/status/report", Web);
            Assert.Equal(new StatusPageDto("project-status.md", false, null, false), none);

            (await http.PostAsync("/api/status/report", null)).EnsureSuccessStatusCode();
            var today = DateOnly.FromDateTime(DateTime.Now);
            var fresh = await http.GetFromJsonAsync<StatusPageDto>("/api/status/report", Web);
            Assert.Equal(new StatusPageDto("project-status.md", true, today.ToString("yyyy-MM-dd"), false), fresh);

            var target = Path.Combine(_root, "project-status.md");
            var old = today.AddDays(-2).ToString("yyyy-MM-dd");
            await File.WriteAllTextAsync(target, (await File.ReadAllTextAsync(target)).Replace($"Generated {today:yyyy-MM-dd}", $"Generated {old}"));
            var stale = await http.GetFromJsonAsync<StatusPageDto>("/api/status/report", Web);
            Assert.Equal(new StatusPageDto("project-status.md", true, old, true), stale);
        });

    [Fact]
    public async Task Get_ignores_a_file_knit_did_not_write() =>
        await WithApi(async http =>
        {
            await File.WriteAllTextAsync(Path.Combine(_root, "project-status.md"), "# Ours\n");
            var dto = await http.GetFromJsonAsync<StatusPageDto>("/api/status/report", Web);
            Assert.False(dto!.Exists);
            Assert.False(dto.Stale);
        });

    private async Task WithApi(Func<HttpClient, Task> body)
    {
        var port = GetFreePort();
        var app = WebApiBuilder.Build([], new WebApiOptions
        {
            RootPath = _root,
            Port = port,
            OpenBrowser = false,
            EnableStaticFiles = false,
            EnableWatch = false,
            EnableSearch = false,
        });
        await app.StartAsync();
        try
        {
            using var http = TestApi.Client(port);
            await body(http);
        }
        finally
        {
            await app.StopAsync();
            await app.DisposeAsync();
        }
    }

    private static int GetFreePort()
    {
        var listener = new TcpListener(IPAddress.Loopback, 0);
        listener.Start();
        var port = ((IPEndPoint)listener.LocalEndpoint).Port;
        listener.Stop();
        return port;
    }
}
