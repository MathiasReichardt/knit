using System.Text.Json;
using System.Text.RegularExpressions;

namespace Knit.Cli.Tests;

/// <summary>
/// `knit status report`: where the page lands, the overwrite
/// guard, and that every link in it opens a file. The page itself is pinned in
/// <see cref="StatusPageRendererTests"/>.
/// </summary>
[Collection(nameof(CliCollection))]
public partial class StatusReportCliTests
{
    private static TempKnitRoot Init()
    {
        var root = new TempKnitRoot();
        Assert.Equal(0, root.Run("init", "--handle", "a", "--display", "A", "--non-interactive").ExitCode);
        return root;
    }

    private static string Add(TempKnitRoot root, params string[] args)
    {
        var r = root.Run(["add", .. args, "--json"]);
        Assert.Equal(0, r.ExitCode);
        return JsonDocument.Parse(r.Stdout).RootElement.GetProperty("id").GetString()!;
    }

    /// <summary>A repo touching every link kind: item, readme, roadmap, milestone, design, ADR.</summary>
    private static TempKnitRoot Seeded()
    {
        var root = Init();
        Assert.Equal(0, root.Run("project", "new", "web", "--title", "Website", "--roadmap").ExitCode);
        Assert.Equal(0, root.Run("project", "milestone", "new", "web", "beta", "--title", "Beta", "--target", "2000-01-01").ExitCode);
        var project = Add(root, "project", "Website");
        Assert.Equal(0, root.Run("set", project, "project=web").ExitCode);
        var epic = Add(root, "epic", "Shop", "--parent", project);
        Assert.Equal(0, root.Run("link", epic, "--milestone", "beta").ExitCode);
        Add(root, "bug", "Loose bug");
        Assert.Equal(0, root.Run("design", "new", "search", "--title", "Search").ExitCode);
        Assert.Equal(0, root.Run("kb", "add", "adr", "Pick a store").ExitCode);
        return root;
    }

    private static string Page(TempKnitRoot root, string rel = "project-status.md") =>
        File.ReadAllText(Path.Combine(root.Path, rel));

    [GeneratedRegex(@"\]\(([^)#]+)\)")]
    private static partial Regex LinkTarget();

    private static void AssertLinksResolve(string page, string fromDir)
    {
        var targets = LinkTarget().Matches(page).Select(m => m.Groups[1].Value).ToList();
        Assert.NotEmpty(targets);
        foreach (var t in targets)
            Assert.True(File.Exists(Path.Combine(fromDir, Uri.UnescapeDataString(t))), $"dangling link {t}");
    }

    [Fact]
    public void Writes_the_page_at_the_repo_root_and_every_link_resolves()
    {
        using var root = Seeded();
        var r = root.Run("status", "report", "--json");
        Assert.Equal(0, r.ExitCode);
        var json = JsonDocument.Parse(r.Stdout).RootElement;
        Assert.Equal(Path.Combine(root.Path, "project-status.md"), json.GetProperty("path").GetString());
        Assert.True(json.GetProperty("written").GetBoolean());

        var page = Page(root);
        Assert.StartsWith("<!-- generated by knit status report — do not edit -->\n", page);
        Assert.Contains("[Readme](.knit/projects/web/readme.md)", page);
        Assert.Contains("[Roadmap](.knit/projects/web/roadmap.md)", page);
        Assert.Contains("[Search](.knit/designs/search-design.md)", page);
        Assert.Contains("ADR 0001", page);
        AssertLinksResolve(page, root.Path);
    }

    [Fact]
    public void A_second_run_on_the_same_day_is_byte_identical()
    {
        using var root = Seeded();
        Assert.Equal(0, root.Run("status", "report").ExitCode);
        var first = File.ReadAllBytes(Path.Combine(root.Path, "project-status.md"));
        Assert.Equal(0, root.Run("status", "report").ExitCode);
        Assert.Equal(first, File.ReadAllBytes(Path.Combine(root.Path, "project-status.md")));
    }

    [Fact]
    public void A_file_without_the_marker_is_refused_and_force_overwrites_it()
    {
        using var root = Init();
        var target = Path.Combine(root.Path, "project-status.md");
        File.WriteAllText(target, "# Our status\n\nHand-written.\n");

        var refused = root.Run("status", "report");
        Assert.Equal(4, refused.ExitCode);
        Assert.Contains("--force", refused.Stderr);
        Assert.Equal("# Our status\n\nHand-written.\n", File.ReadAllText(target));

        Assert.Equal(0, root.Run("status", "report", "--force").ExitCode);
        Assert.StartsWith("<!-- generated by knit status report", File.ReadAllText(target));
    }

    [Fact]
    public void The_config_key_moves_the_page_and_its_links_resolve_from_there()
    {
        using var root = Seeded();
        Assert.Equal(0, root.Run("config", "set", "status_report.path", "docs/status.md").ExitCode);
        Assert.Equal(0, root.Run("status", "report").ExitCode);

        var page = Page(root, Path.Combine("docs", "status.md"));
        Assert.Contains("](../.knit/items/", page);
        AssertLinksResolve(page, Path.Combine(root.Path, "docs"));
        Assert.False(File.Exists(Path.Combine(root.Path, "project-status.md")));
    }

    [Fact]
    public void Out_beats_the_config_key()
    {
        using var root = Init();
        Assert.Equal(0, root.Run("config", "set", "status_report.path", "docs/status.md").ExitCode);
        Assert.Equal(0, root.Run("status", "report", "--out", "other.md").ExitCode);
        Assert.True(File.Exists(Path.Combine(root.Path, "other.md")));
        Assert.False(File.Exists(Path.Combine(root.Path, "docs", "status.md")));
    }

    [Theory]
    [InlineData("../outside.md")]
    [InlineData(".knit/status.md")]
    public void A_target_outside_the_repo_or_inside_knit_is_refused(string path)
    {
        using var root = Init();
        var r = root.Run("status", "report", "--out", path);
        Assert.Equal(2, r.ExitCode);
        Assert.Contains("--out", r.Stderr);
        Assert.False(File.Exists(Path.GetFullPath(Path.Combine(root.Path, path))));
    }

    [Fact]
    public void A_config_key_outside_the_repo_is_refused_on_set_and_on_use()
    {
        using var root = Init();
        Assert.Equal(2, root.Run("config", "set", "status_report.path", "../x.md").ExitCode);

        // A hand edit gets past `config set`; the command still refuses it.
        var config = Path.Combine(root.Path, ".knit", "config.json");
        var node = System.Text.Json.Nodes.JsonNode.Parse(File.ReadAllText(config))!.AsObject();
        node["status_report.path"] = "../x.md";
        File.WriteAllText(config, node.ToJsonString());
        var r = root.Run("status", "report");
        Assert.Equal(2, r.ExitCode);
        Assert.Contains("status_report.path", r.Stderr);
        Assert.False(File.Exists(Path.GetFullPath(Path.Combine(root.Path, "..", "x.md"))));
    }

    [Fact]
    public void An_archived_design_is_hidden()
    {
        using var root = Init();
        Assert.Equal(0, root.Run("design", "new", "old", "--title", "Old plan").ExitCode);
        Assert.Equal(0, root.Run("design", "archive", "old").ExitCode);
        Assert.DoesNotContain("Old plan", root.Run("status", "report", "--stdout").Stdout);
    }

    [Fact]
    public void Stdout_prints_the_page_and_writes_nothing()
    {
        using var root = Init();
        var r = root.Run("status", "report", "--stdout");
        Assert.Equal(0, r.ExitCode);
        Assert.StartsWith("<!-- generated by knit status report", r.Stdout);
        Assert.False(File.Exists(Path.Combine(root.Path, "project-status.md")));
    }

    [Fact]
    public void Under_a_redirect_the_page_lands_in_the_knit_roots_repo()
    {
        using var root = new TempKnitRoot();
        Environment.SetEnvironmentVariable("KNIT_ROOT", null);
        string Repo(string name)
        {
            var dir = Path.Combine(root.Path, name);
            Directory.CreateDirectory(Path.Combine(dir, ".git"));
            Assert.Equal(0, RunIn(root, dir, "init", "--handle", "t", "--display", "T", "--non-interactive").ExitCode);
            return dir;
        }
        var checkout = Repo("checkout");
        var target = Repo("target");
        Assert.Equal(0, RunIn(root, checkout, "root", target).ExitCode);

        Assert.Equal(0, RunIn(root, checkout, "status", "report").ExitCode);
        Assert.True(File.Exists(Path.Combine(target, "project-status.md")));
        Assert.False(File.Exists(Path.Combine(checkout, "project-status.md")));
    }

    private static CliResult RunIn(TempKnitRoot root, string dir, params string[] args)
    {
        Directory.SetCurrentDirectory(dir);
        try { return root.Run(args); }
        finally { Directory.SetCurrentDirectory(root.Path); }
    }
}
