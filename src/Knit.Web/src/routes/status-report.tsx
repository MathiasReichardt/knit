import { createFileRoute } from '@tanstack/react-router'
import { useQuery } from '@tanstack/react-query'
import { FileWarning, RefreshCw } from 'lucide-react'
import { fileApi, fileQk } from '../api/file'
import { ApiError } from '../api/client'
import { pageFolder } from '../api/status'
import { useStatusPage, useWriteStatusReport } from '../hooks/useStatusPage'
import { MarkdownRender } from '../components/MarkdownRender'
import { ReadOnlyBadge } from '../components/ReadOnlyBadge'
import { StaleDot } from '../components/StaleDot'

export const Route = createFileRoute('/status-report')({
  component: StatusReportScreen,
})

/**
 * The generated status page, rendered. Read-only: the next run would drop an
 * edit. Its links are relative to the page's folder and resolve to the item,
 * project, design or KB entry they point at.
 */
function StatusReportScreen() {
  const page = useStatusPage()
  const { write, writing } = useWriteStatusReport()
  const path = page.data?.exists ? page.data.path : null
  const file = useQuery({
    queryKey: fileQk.view(path ?? ''),
    queryFn: () => fileApi.view(path!),
    enabled: path !== null,
    retry: false,
  })

  return (
    <div className="flex flex-col h-full min-h-0">
      <div className="px-4 py-3 border-b border-zinc-200 dark:border-zinc-800 flex items-center gap-2 text-xs text-zinc-500">
        <span className="font-mono">{page.data?.path}</span>
        {path && <ReadOnlyBadge reason="Generated by knit status report; an edit would be lost on the next run" />}
        {page.data?.exists && (
          <span className="inline-flex items-center gap-1.5">
            {page.data.generated ? `Generated ${page.data.generated}` : 'No Generated date'}
            {page.data.stale && <StaleDot generated={page.data.generated} />}
          </span>
        )}
        <button
          type="button"
          disabled={writing}
          onClick={() => { void write() }}
          className="ml-auto inline-flex items-center gap-1.5 rounded-md border border-zinc-300 dark:border-zinc-700 px-2 py-1 text-zinc-700 dark:text-zinc-300 hover:bg-zinc-100 dark:hover:bg-zinc-800 disabled:opacity-50"
        >
          <RefreshCw className={`h-3.5 w-3.5 ${writing ? 'animate-spin' : ''}`} aria-hidden />
          Regenerate
        </button>
      </div>
      <div className="flex-1 min-h-0 overflow-auto p-6">
        {page.isLoading && <div className="text-sm text-zinc-500">Loading…</div>}
        {page.data && !page.data.exists && (
          <Placeholder
            title="No status page"
            detail={`Nothing knit wrote is at ${page.data.path}. Regenerate writes it there.`}
          />
        )}
        {file.error && <Placeholder title="Failed to load the page" detail={errorDetail(file.error)} />}
        {file.data && path && (
          <div className="mx-auto max-w-4xl">
            <MarkdownRender body={file.data.content} linkParent={pageFolder(path)} forgeAnchors trackSection />
          </div>
        )}
      </div>
    </div>
  )
}

function errorDetail(error: unknown): string {
  if (error instanceof ApiError) return error.problem?.detail ?? `HTTP ${error.status}`
  return error instanceof Error ? error.message : String(error)
}

function Placeholder({ title, detail }: { title: string; detail: string }) {
  return (
    <div className="rounded border border-dashed border-zinc-300 dark:border-zinc-700 p-8 flex flex-col items-center gap-2 text-center">
      <FileWarning className="h-8 w-8 text-zinc-400" />
      <div className="text-sm font-medium text-zinc-700 dark:text-zinc-200">{title}</div>
      <div className="text-xs text-zinc-500 max-w-md">{detail}</div>
    </div>
  )
}
