        private void Designs()
        {
            Line("## Designs");
            Line();
            var shown = _in.Designs.Where(d => !Hidden(d)).ToList();
            if (shown.Count == 0)
            {
                Line("No open designs.");
                Line();
                return;
            }
            TableHead("Design", "Status");
            foreach (var d in shown) Row(Link(GfmText.Escape(d.Title), d.Path), GfmText.Escape(d.Status));
            Line();
        }

        private bool Hidden(StatusPageDesign d)
        {
            if (d.Status is { } s && s.TrimStart().StartsWith("superseded", StringComparison.OrdinalIgnoreCase)) return true;
            var items = _in.Items.Where(i => string.Equals(i.Design, d.Slug, StringComparison.Ordinal)).ToList();
            return items.Count > 0 && items.All(i => !IsOpen(i));
        }
