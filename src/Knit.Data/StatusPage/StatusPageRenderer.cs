        private sealed class LateLeaves
        {
            public int TasksOverdue, TasksAtRisk, TodosOverdue, TodosAtRisk;
            public DateOnly? Earliest;

            public void Add(Item leaf, bool overdue, DateOnly? date)
            {
                if (leaf.Type == ItemType.Task) { if (overdue) TasksOverdue++; else TasksAtRisk++; }
                else if (overdue) TodosOverdue++;
                else TodosAtRisk++;
                if (date is { } d && (Earliest is null || d < Earliest)) Earliest = d;
            }
        }

        private void Deadlines()
        {
            Line("## Deadlines");
            Line();
            var limit = _today.AddDays(DeadlineWindowDays);
            var rows = new List<(DateOnly? Date, int Kind, int Pos, string What, string Priority, string Risk)>();

            var milestonePos = 0;
            foreach (var m in _milestones.Values.OrderBy(m => m.QualifiedSlug, StringComparer.Ordinal))
            {
                milestonePos++;
                if (m.State != MilestoneState.Planned || m.Target is not { } t) continue;
                var open = Linked(m).Count(IsOpen);
                var passed = t < _today;
                if (passed ? open == 0 : t >= limit) continue;
                var risk = new List<string>();
                if (passed) risk.Add("⚠ target passed");
                if (open > 0) risk.Add($"{open} open");
                rows.Add((t, 0, milestonePos, $"🏁 {Link(GfmText.Escape(m.Title), m.Path)}", "", string.Join(" · ", risk)));
            }

            static bool Container(Item i) => i.Type is ItemType.Epic or ItemType.Feature or ItemType.Bug;
            var leaves = new Dictionary<string, LateLeaves>(StringComparer.Ordinal);
            var candidates = new HashSet<string>(StringComparer.Ordinal);
            foreach (var i in _in.Items.Where(i => IsOpen(i) && Container(i)))
                if (Overdue(i) || AtRisk(i) || i.Due is { } d && d >= _today && d < limit)
                    candidates.Add(i.Id);
            foreach (var leaf in _in.Items.Where(i => i.Type is ItemType.Task or ItemType.Todo && Late(i)))
            {
                var holder = NearestOpenContainer(leaf) ?? leaf;
                candidates.Add(holder.Id);
                if (holder.Id == leaf.Id) continue;
                if (!leaves.TryGetValue(holder.Id, out var l)) leaves[holder.Id] = l = new LateLeaves();
                l.Add(leaf, Overdue(leaf), leaf.Due ?? Risk(leaf).ImpliedDeadline);
            }

            foreach (var id in candidates)
            {
                var i = _graph.Get(id)!;
                var l = leaves.GetValueOrDefault(id);
                var risk = Risk(i);
                var date = i.Due ?? risk.ImpliedDeadline ?? l?.Earliest;
                var parts = new List<string>();
                var overdue = Overdue(i);
                if (overdue) parts.Add("⚠ overdue");
                if (risk is { AtRisk: true, ImpliedDeadline: { } needed })
                    parts.Add($"{(overdue ? "" : "⚠ ")}at risk: needed by {Date(needed)}{RiskSource(i, needed)}");
                if (i.IsBlocked) parts.Add("⛔");
                if (l is not null) parts.AddRange(Rollup(l.TasksOverdue, l.TasksAtRisk, l.TodosOverdue, l.TodosAtRisk));
                rows.Add((date, 1, Pos(i), $"{Emoji(i.Type)} {ItemLink(i)}",
                    i.Priority == Priority.Normal ? "" : i.Priority.ToWire(), string.Join(" · ", parts)));
            }

            if (rows.Count == 0)
            {
                Line($"Nothing is overdue, at risk or due before {Date(limit)}.");
                Line();
                return;
            }

            Line($"Overdue, at risk, or due before {Date(limit)}. Late tasks are counted on the feature, epic or bug they belong to.");
            Line();
            TableHead("Date", "What", "Priority", "Risk");
            foreach (var r in rows
                         .OrderBy(r => r.Date is null ? 1 : 0)
                         .ThenBy(r => r.Date)
                         .ThenBy(r => r.Kind)
                         .ThenBy(r => r.Pos))
                Row(r.Date is { } d ? Date(d) : "", r.What, r.Priority, r.Risk);
            Line();
        }

        private Item? NearestOpenContainer(Item leaf)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal) { leaf.Id };
            var id = leaf.Parent;
            while (!string.IsNullOrEmpty(id) && seen.Add(id) && _graph.Get(id) is { } p)
            {
                if (p.Type is ItemType.Epic or ItemType.Feature or ItemType.Bug && IsOpen(p)) return p;
                id = p.Parent;
            }
            return null;
        }

        /// <summary>Where an implied deadline comes from: the item's own milestone, else the item it blocks.</summary>
        private string RiskSource(Item i, DateOnly needed)
        {
            if (_milestoneDeadlines.TryGetValue(i.Id, out var target) && target == needed
                && _effective.TryGetValue(i.Id, out var e) && _milestones.TryGetValue(e.QualifiedSlug, out var m))
                return $" ({GfmText.Escape(m.Title)})";
            foreach (var x in _graph.BlockedTargetsOf(i.Id).Select(_graph.Get).OfType<Item>().Where(IsOpen).OrderBy(Pos))
            {
                var xDeadline = Min(x.Due, Risk(x).ImpliedDeadline);
                if (xDeadline == needed) return $" (blocks {GfmText.Escape(x.Title)})";
            }
            return "";
        }

        private static DateOnly? Min(DateOnly? a, DateOnly? b) =>
            a is null ? b : b is null ? a : a < b ? a : b;

