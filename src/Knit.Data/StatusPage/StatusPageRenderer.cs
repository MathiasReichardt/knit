using System.Text;
using Knit.Core.Domain;
using Knit.Core.Projects;

namespace Knit.Data.StatusPage;

/// <summary>
/// Renders <c>project-status.md</c>: a page for
/// readers who don't use Knit, derived by code alone. Every sentence is a
/// fixed template filled with data, and the same data on the same day gives
/// the same bytes.
/// </summary>
public static class StatusPageRenderer
{
    public const string Marker = "<!-- generated by knit status report — do not edit -->";
    public const string GeneratedPrefix = "Generated ";
    private const int AttentionCap = 10;
    private const int DeadlineWindowDays = 42;

    public static string Render(StatusPageInput input) => new Page(input).Render();

    private sealed class Page
    {
        private readonly StatusPageInput _in;
        private readonly DateOnly _today;
        private readonly LinkGraph _graph;
        private readonly IReadOnlyDictionary<string, MilestoneInheritance.Effective> _effective;
        private readonly IReadOnlyDictionary<string, DateOnly> _milestoneDeadlines;
        private readonly IReadOnlyDictionary<string, DeadlineRisk.ItemRisk> _risk;
        private readonly Dictionary<string, MilestoneDoc> _milestones = new(StringComparer.Ordinal);
        private readonly Dictionary<string, int> _pos = new(StringComparer.Ordinal);
        private readonly StringBuilder _sb = new();

        public Page(StatusPageInput input)
        {
            _in = input;
            _today = input.Today;
            _graph = new LinkGraph(input.Items);
            _effective = MilestoneInheritance.Compute(input.Items);
            foreach (var m in input.Folders.SelectMany(f => f.Milestones)) _milestones.TryAdd(m.QualifiedSlug, m);

            var deadlines = new Dictionary<string, DateOnly>(StringComparer.Ordinal);
            foreach (var (id, e) in _effective)
                if (_milestones.TryGetValue(e.QualifiedSlug, out var m) && m.Target is { } t) deadlines[id] = t;
            _milestoneDeadlines = deadlines;
            _risk = DeadlineRisk.Compute(_graph, deadlines);

            foreach (var item in TreeOrder()) _pos[item.Id] = _pos.Count;
        }

        // ---------------------------------------------------------------- order

        private IEnumerable<Item> Sorted(IEnumerable<Item> items) => items
            .OrderBy(i => i.Rank is null ? 1 : 0)
            .ThenBy(i => i.Rank ?? "", StringComparer.Ordinal)
            .ThenBy(i => i.Title, StringComparer.Ordinal)
            .ThenBy(i => i.Id, StringComparer.Ordinal);

        private IEnumerable<Item> Children(Item item) =>
            Sorted(_graph.ChildrenOf(item.Id).Select(_graph.Get).OfType<Item>());

        /// <summary>Depth-first by rank — "rank order" everywhere on the page.</summary>
        private List<Item> TreeOrder()
        {
            var seen = new HashSet<string>(StringComparer.Ordinal);
            var order = new List<Item>();
            void Walk(Item i)
            {
                if (!seen.Add(i.Id)) return;
                order.Add(i);
                foreach (var c in Children(i)) Walk(c);
            }
            foreach (var r in Sorted(_graph.Roots())) Walk(r);
            // A parent cycle has no root; its members still get a place.
            foreach (var i in Sorted(_graph.Items)) Walk(i);
            return order;
        }

        private int Pos(Item i) => _pos.GetValueOrDefault(i.Id, int.MaxValue);

        // ---------------------------------------------------------------- facts

        private static bool IsOpen(Item i) => LinkGraph.IsOpen(i);

        private bool Overdue(Item i) => DueDates.Status(i.Due, i.State, _today, 0) == DueStatus.Overdue;

        private DeadlineRisk.ItemRisk Risk(Item i) =>
            _risk.GetValueOrDefault(i.Id) ?? new DeadlineRisk.ItemRisk(null, false, []);

        private bool AtRisk(Item i) => Risk(i).AtRisk;

        private bool Late(Item i) => IsOpen(i) && (Overdue(i) || AtRisk(i));

        private int DaysSince(DateOnly d) => _today.DayNumber - d.DayNumber;

        /// <summary>Strict descendants, stopping at nested projects — they get their own section.</summary>
        private List<Item> Below(Item item)
        {
            var result = new List<Item>();
            var seen = new HashSet<string>(StringComparer.Ordinal) { item.Id };
            var stack = new Stack<Item>(Children(item).Reverse());
            while (stack.Count > 0)
            {
                var i = stack.Pop();
                if (!seen.Add(i.Id) || i.Type == ItemType.Project) continue;
                result.Add(i);
                foreach (var c in Children(i).Reverse()) stack.Push(c);
            }
            return result;
        }

        /// <summary>The nearest project strictly above the item; null outside every project.</summary>
        private Item? ProjectAbove(Item item)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal) { item.Id };
            var id = item.Parent;
            while (!string.IsNullOrEmpty(id) && seen.Add(id) && _graph.Get(id) is { } p)
            {
                if (p.Type == ItemType.Project) return p;
                id = p.Parent;
            }
            return null;
        }

        private bool HasParent(Item i) => !string.IsNullOrEmpty(i.Parent) && _graph.Get(i.Parent!) is not null;

        /// <summary>Open items below a blocked one — what its block holds up.</summary>
        private int HeldUp(Item blocked) => _graph.Subtree(blocked.Id).Count(i => i.Id != blocked.Id && IsOpen(i));

        private static (int Done, int Total) Count(IEnumerable<Item> items)
        {
            int done = 0, total = 0;
            foreach (var i in items)
            {
                if (i.State == ItemState.Dismissed) continue;
                total++;
                if (i.State == ItemState.Done) done++;
            }
            return (done, total);
        }

        private List<(MilestoneDoc Doc, int Open, int Total)> PassedMilestones() => _milestones.Values
            .Where(m => m is { State: MilestoneState.Planned, Target: { } t } && t < _today)
            .Select(m =>
            {
                var linked = Linked(m);
                return (m, linked.Count(IsOpen), Count(linked).Total);
            })
            .Where(x => x.Item2 > 0)
            .OrderBy(x => x.m.Target)
            .ThenBy(x => x.m.QualifiedSlug, StringComparer.Ordinal)
            .ToList();

        private List<Item> Linked(MilestoneDoc m) => _in.Items
            .Where(i => _effective.TryGetValue(i.Id, out var e) && e.Is(m.ProjectSlug, m.Slug))
            .ToList();

        // ---------------------------------------------------------------- text

        private static string Date(DateOnly d) => DueDates.ToWire(d);

        private static string Plural(int n, string one, string many) => n == 1 ? one : many;

        private static string Items(int n) => $"{n} {Plural(n, "item", "items")}";

        private static string Days(int n) => $"{n} {Plural(n, "day", "days")}";

        private static string Emoji(ItemType t) => t switch
        {
            ItemType.Project => "🎯",
            ItemType.Epic => "⚡",
            ItemType.Feature => "✨",
            ItemType.Bug => "🐞",
            ItemType.Task => "🔧",
            _ => "📝",
        };

        private static string HealthWord(Health h) => h switch
        {
            Health.OnTrack => "on track",
            Health.AtRisk => "at risk",
            _ => "off track",
        };

        private string Link(string text, string absolutePath) =>
            $"[{text}]({GfmText.Url(Path.GetRelativePath(_in.ReportDir, absolutePath))})";

        private string ItemLink(Item i) =>
            _in.ItemPaths.TryGetValue(i.Id, out var p) ? Link(GfmText.Escape(i.Title), p) : GfmText.Escape(i.Title);

        private string ShortLink(Item i) =>
            _in.ItemPaths.TryGetValue(i.Id, out var p) ? Link(_in.ShortId(i.Id), p) : _in.ShortId(i.Id);

        /// <summary>Non-breaking spaces glue bar and count: a narrow table column widens instead of wrapping "1 / 14" under the bar.</summary>
        private const char Nbsp = (char)0xA0;

        /// <summary>
        /// Emoji squares, not block glyphs: both come from the emoji font, so the
        /// cells match in height whatever font a viewer draws text or code in.
        /// </summary>
        private static string Bar(int done, int total)
        {
            const int cells = 5;
            var filled = (int)Math.Round(done * (double)cells / total, MidpointRounding.AwayFromZero);
            if (done > 0) filled = Math.Max(filled, 1);
            if (done < total) filled = Math.Min(filled, cells - 1);
            return string.Concat(Enumerable.Repeat("🟩", filled)) + string.Concat(Enumerable.Repeat("⬜", cells - filled))
                + $"{Nbsp}{done}{Nbsp}/{Nbsp}{total}";
        }

        private static string BugSplit(IEnumerable<Item> bugs)
        {
            var list = bugs.ToList();
            return string.Join(" · ", new[] { Priority.Critical, Priority.Important, Priority.Normal, Priority.Someday }
                .Select(p => (p, n: list.Count(b => b.Priority == p)))
                .Where(x => x.n > 0)
                .Select(x => $"{x.n} {x.p.ToWire()}"));
        }

        private void Line(string text = "") => _sb.Append(text).Append('\n');

        private void Row(params string[] cells)
        {
            _sb.Append('|');
            foreach (var c in cells) _sb.Append(c.Length == 0 ? " |" : $" {c} |");
            _sb.Append('\n');
        }

        private void TableHead(params string[] heads)
        {
            Row(heads);
            Line("|" + string.Concat(heads.Select(_ => "---|")));
        }

        // ---------------------------------------------------------------- page

        public string Render()
        {
            var sections = ProjectSections();
            var slugger = new GfmText.Slugger();
            var title = $"{_in.RepoName} — project status";
            slugger.Next(title);
            var minute = slugger.Next("In one minute");
            var attention = slugger.Next("Needs attention");
            var projects = slugger.Next("Projects");
            foreach (var s in sections) s.Anchor = slugger.Next(s.Title);
            var deadlines = slugger.Next("Deadlines");
            var designs = slugger.Next("Designs");

            Line(Marker);
            Line($"# {GfmText.Escape(title)}");
            Line();
            Line($"{GeneratedPrefix}{Date(_today)} · for the full tracker run `knit web` in this repo");
            Line();
            Line($"[In one minute](#{minute}) · [Needs attention](#{attention}) · [Projects](#{projects}) · " +
                 $"[Deadlines](#{deadlines}) · [Designs](#{designs})");
            Line();
            Line("🎯 project · ⚡ epic · ✨ feature · 🐞 bug · 🔧 task · 📝 todo · 🏁 milestone · ⛔ blocked · ⚠ overdue / at risk");
            Line();

            InOneMinute();
            NeedsAttention();
            Projects(sections);
            Deadlines();
            Designs();

            var text = _sb.ToString().TrimEnd('\n');
            return text + "\n";
        }

        // ------------------------------------------------------- in one minute

        private void InOneMinute()
        {
            Line("## In one minute");
            Line();
            var lines = new List<string>();

            var passed = PassedMilestones();
            if (passed.Count == 1)
            {
                var (m, mOpen, total) = passed[0];
                lines.Add($"🏁 **{GfmText.Escape(m.Title)} is past its target:** {Date(m.Target!.Value)}, " +
                          $"{Days(DaysSince(m.Target.Value))} ago, with {mOpen} of {Items(total)} open.");
            }
            else if (passed.Count > 1)
            {
                var shown = passed.Take(2).Select(x =>
                    $"{GfmText.Escape(x.Doc.Title)} ({Date(x.Doc.Target!.Value)}, {Days(DaysSince(x.Doc.Target.Value))} ago, " +
                    $"{x.Open} of {x.Total} open)");
                var more = passed.Count > 2 ? $" and {passed.Count - 2} more" : "";
                lines.Add($"🏁 **{passed.Count} milestones are past their targets:** {string.Join(" · ", shown)}{more}.");
            }

            var overdue = _in.Items.Where(Overdue).OrderBy(i => i.Due).ThenBy(Pos).ToList();
            if (overdue.Count > 0)
            {
                var oldest = overdue[0];
                lines.Add($"⚠ **{Items(overdue.Count)} {Plural(overdue.Count, "is", "are")} overdue.** " +
                          $"The oldest is {ItemLink(oldest)}, {Days(DaysSince(oldest.Due!.Value))} late.");
            }

            var blocked = _in.Items.Where(i => IsOpen(i) && i.IsBlocked).ToList();
            if (blocked.Count > 0)
            {
                var blockedIds = blocked.Select(b => b.Id).ToHashSet(StringComparer.Ordinal);
                var held = blocked
                    .SelectMany(b => _graph.Subtree(b.Id))
                    .Where(i => IsOpen(i) && !blockedIds.Contains(i.Id))
                    .Select(i => i.Id)
                    .Distinct(StringComparer.Ordinal)
                    .Count();
                var holding = held > 0 ? $", holding up {held} more" : "";
                lines.Add($"⛔ **{Items(blocked.Count)} {Plural(blocked.Count, "is", "are")} blocked**{holding}.");
            }

            var open = _in.Items.Where(IsOpen).ToList();
            var unowned = open.Count(i => string.IsNullOrEmpty(i.Assignee));
            if (unowned > 0)
                lines.Add($"👤 **{unowned} of {open.Count} open {Plural(open.Count, "item", "items")} " +
                          $"{Plural(unowned, "has", "have")} no owner.**");

            var bugs = open.Where(i => i.Type == ItemType.Bug).ToList();
            if (bugs.Count > 0)
                lines.Add($"🐞 **{bugs.Count} open {Plural(bugs.Count, "bug", "bugs")}:** {BugSplit(bugs)}.");

            if (lines.Count == 0) Line("Nothing is overdue, blocked or at risk.");
            else foreach (var l in lines) Line($"- {l}");
            Line();
        }

        // ----------------------------------------------------- needs attention

        private void NeedsAttention()
        {
            Line("## Needs attention");
            Line();
            var hits = new List<(string Sentence, string Link)>();
            hits.AddRange(R1PassedMilestones());
            hits.AddRange(R2BlockedHoldingUp());
            hits.AddRange(R3OverdueImportant());
            hits.AddRange(R4ReviewUnassigned());
            hits.AddRange(R5LooseBugs());
            hits.AddRange(R6ProposedDecisions());

            if (hits.Count == 0)
            {
                Line("Nothing needs attention.");
                Line();
                return;
            }

            var n = 0;
            foreach (var (sentence, link) in hits.Take(AttentionCap))
            {
                var prefix = $"{++n}. ";
                Line(prefix + sentence);
                Line(new string(' ', prefix.Length) + link);
            }
            if (hits.Count > AttentionCap)
            {
                Line();
                Line($"…and {hits.Count - AttentionCap} more.");
            }
            Line();
        }

        private IEnumerable<(string, string)> R1PassedMilestones() => PassedMilestones().Select(x =>
            ($"🏁 **{GfmText.Escape(x.Doc.Title)} is past its target with work open.** " +
             $"The target was {Date(x.Doc.Target!.Value)}; {Items(x.Open)} {Plural(x.Open, "is", "are")} open.",
             Link("Milestone", x.Doc.Path)));

        private IEnumerable<(string, string)> R2BlockedHoldingUp() => _in.Items
            .Where(i => IsOpen(i) && i.IsBlocked)
            .Select(i => (Item: i, Held: HeldUp(i)))
            .Where(x => x.Held > 0)
            .OrderBy(x => Pos(x.Item))
            .Select(x =>
                ($"⛔ **{GfmText.Escape(x.Item.Title)} is blocked and holds up {x.Held} open {Plural(x.Held, "item", "items")}.** " +
                 $"Reason: \"{GfmText.Escape(x.Item.BlockedSummary)}\".",
                 ShortLink(x.Item)));

        private IEnumerable<(string, string)> R3OverdueImportant() => _in.Items
            .Where(i => Overdue(i) && i.Priority >= Priority.Important)
            .OrderBy(Pos)
            .Select(i =>
            {
                var owner = string.IsNullOrEmpty(i.Assignee) ? "No owner." : $"Owner: {GfmText.Escape(i.Assignee)}.";
                var blocks = _graph.BlockedTargetsOf(i.Id).Select(_graph.Get).OfType<Item>().Where(IsOpen)
                    .OrderBy(Pos).Select(b => GfmText.Escape(b.Title)).ToList();
                var tail = blocks.Count > 0 ? $" It blocks {string.Join(", ", blocks)}." : "";
                if (i.IsBlocked) tail += " It is itself blocked.";
                return ($"⚠ **{GfmText.Escape(i.Title)} is {i.Priority.ToWire()} and {Days(DaysSince(i.Due!.Value))} overdue.** {owner}{tail}",
                    ShortLink(i));
            });

        private IEnumerable<(string, string)> R4ReviewUnassigned() => _in.Items
            .Where(i => i.State == ItemState.Review && string.IsNullOrEmpty(i.Assignee))
            .OrderBy(Pos)
            .Select(i => ($"👀 **{GfmText.Escape(i.Title)} is in review with no assignee.**", ShortLink(i)));

        private IEnumerable<(string, string)> R5LooseBugs() => _in.Items
            .Where(i => i.Type == ItemType.Bug && IsOpen(i) && string.IsNullOrEmpty(i.Assignee) && !HasParent(i))
            .OrderBy(Pos)
            .Select(i => ($"🐞 **{GfmText.Escape(i.Title)} is a bug with no owner and no parent.**", ShortLink(i)));

        private IEnumerable<(string, string)> R6ProposedDecisions() => _in.Adrs
            .Where(a => a.Status.Trim().Equals("proposed", StringComparison.OrdinalIgnoreCase))
            .Select(a => (a.Date is { } d
                    ? $"📜 **The decision \"{GfmText.Escape(a.Title)}\" has been proposed since {Date(d)}** ({Days(DaysSince(d))})."
                    : $"📜 **The decision \"{GfmText.Escape(a.Title)}\" is proposed.**",
                Link($"ADR {GfmText.Escape(a.Label)}", a.Path)));

        // ------------------------------------------------------------ projects

        private sealed class Section
        {
            public required string Title { get; init; }
            public Item? Project { get; init; }
            public StatusPageFolder? Folder { get; init; }
            public string Anchor { get; set; } = "";
        }

        private sealed class WorkRow
        {
            public required Item Item { get; init; }
            public bool Child { get; init; }
            public int TasksOverdue { get; set; }
            public int TasksAtRisk { get; set; }
            public int TodosOverdue { get; set; }
            public int TodosAtRisk { get; set; }
        }

        /// <summary>One per project item in rank order, then folders no project points at, then everything outside.</summary>
        private List<Section> ProjectSections()
        {
            var sections = new List<Section>();
            var pointed = new HashSet<string>(StringComparer.Ordinal);
            foreach (var p in _in.Items.Where(i => i.Type == ItemType.Project).OrderBy(Pos))
            {
                var folder = string.IsNullOrEmpty(p.Project) ? null : _in.Folders.FirstOrDefault(f => f.Slug == p.Project);
                if (folder is not null) pointed.Add(folder.Slug);
                sections.Add(new Section { Title = p.Title, Project = p, Folder = folder });
            }
            foreach (var f in _in.Folders.Where(f => !pointed.Contains(f.Slug) && f.Milestones.Count > 0))
                sections.Add(new Section { Title = f.Title, Folder = f });
            var (rows, counters) = OutsideWork();
            if (rows.Count > 0 || counters.Count > 0)
                sections.Add(new Section { Title = "Outside any project" });
            return sections;
        }

        private void Projects(List<Section> sections)
        {
            Line("## Projects");
            Line();
            if (sections.Count == 0)
            {
                Line("No open work.");
                Line();
                return;
            }
            Line("Epics and features with their progress. Bugs get a row only when they are late or critical; the rest are counted.");
            Line();
            if (sections.Count > 1)
            {
                foreach (var s in sections) Line($"- [{GfmText.Escape(s.Title)}](#{s.Anchor})");
                Line();
            }

            foreach (var s in sections)
            {
                Line($"### {GfmText.Escape(s.Title)}");
                Line();
                if (s.Project is { } p) ProjectLine(p, s.Folder);
                else if (s.Folder is { } orphan) FolderLine(orphan);
                if (s.Folder is { Milestones.Count: > 0 } f) MilestoneTable(f);
                var (rows, counters) = s.Project is { } proj ? ProjectWork(proj) : s.Folder is null ? OutsideWork() : ([], []);
                WorkTable(rows, counters);
            }
        }

        private void ProjectLine(Item project, StatusPageFolder? folder)
        {
            var parts = new List<string>();
            if (folder?.ReadmePath is { } readme) parts.Add(Link("Readme", readme));
            if (folder?.RoadmapPath is { } roadmap) parts.Add(Link("Roadmap", roadmap));
            if (project.Health is { } h) parts.Add($"health: {HealthWord(h)}");
            parts.Add(ShortLink(project));
            var (done, total) = Count(_graph.Subtree(project.Id).Where(i => i.Id != project.Id));
            parts.Add(total == 0 ? "nothing planned" : $"{Bar(done, total)}{Nbsp}done");
            Line(string.Join(" · ", parts));
            Line();
        }

        private void FolderLine(StatusPageFolder folder)
        {
            var parts = new List<string>();
            if (folder.ReadmePath is { } readme) parts.Add(Link("Readme", readme));
            if (folder.RoadmapPath is { } roadmap) parts.Add(Link("Roadmap", roadmap));
            if (parts.Count == 0) return;
            Line(string.Join(" · ", parts));
            Line();
        }

        private void MilestoneTable(StatusPageFolder folder)
        {
            TableHead("Milestone", "Target", "State", "Progress");
            var ordered = folder.Milestones
                .OrderBy(m => m.Target is null ? 1 : 0)
                .ThenBy(m => m.Target)
                .ThenBy(m => m.Rank ?? "~", StringComparer.Ordinal)
                .ThenBy(m => m.Slug, StringComparer.Ordinal);
            foreach (var m in ordered)
            {
                var state = m.State.ToWire();
                if (m is { State: MilestoneState.Planned, Target: { } t } && t < _today) state += " · ⚠ target passed";
                var (done, total) = Count(Linked(m));
                var progress = total > 0 ? Bar(done, total) : m.State == MilestoneState.Planned ? "nothing linked" : "";
                Row($"🏁 {Link(GfmText.Escape(m.Title), m.Path)}", m.Target is { } d ? Date(d) : "", state, progress);
            }
            Line();
        }

        private (List<WorkRow> Rows, List<string[]> Counters) ProjectWork(Item project)
        {
            var rows = new List<WorkRow>();
            foreach (var c in Children(project)) Visit(c, null, 0, rows, new HashSet<string>(StringComparer.Ordinal));
            var members = Below(project);
            return (rows, Counters(members, members.Where(i => i.Parent == project.Id)));
        }

        private (List<WorkRow> Rows, List<string[]> Counters) OutsideWork()
        {
            var members = _in.Items.Where(i => i.Type != ItemType.Project && ProjectAbove(i) is null).ToList();
            var tops = Sorted(members.Where(i => !HasParent(i))).ToList();
            var rows = new List<WorkRow>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var t in tops) Visit(t, null, 0, rows, seen);
            return (rows, Counters(members, tops));
        }

        private bool ShownContainer(Item i) =>
            i.Type is ItemType.Epic or ItemType.Feature && (IsOpen(i) || Below(i).Any(IsOpen));

        private bool ShownBug(Item i) =>
            i.Type == ItemType.Bug && IsOpen(i) && (Late(i) || i.Priority == Priority.Critical);

        // anchor: 0 = no shown row above, 1 = under a top row, 2 = under a └ row.
        private void Visit(Item item, WorkRow? owner, int anchor, List<WorkRow> rows, HashSet<string> seen)
        {
            if (item.Type == ItemType.Project || !seen.Add(item.Id)) return;

            var childAnchor = anchor;
            if (ShownContainer(item) && anchor < 2 || ShownBug(item))
            {
                var row = new WorkRow { Item = item, Child = anchor > 0 };
                rows.Add(row);
                owner = row;
                childAnchor = anchor == 0 ? 1 : 2;
            }
            else if (item.Type is ItemType.Task or ItemType.Todo && owner is not null && Late(item))
            {
                var overdue = Overdue(item);
                if (item.Type == ItemType.Task)
                {
                    if (overdue) owner.TasksOverdue++; else owner.TasksAtRisk++;
                }
                else if (overdue) owner.TodosOverdue++;
                else owner.TodosAtRisk++;
            }

            foreach (var c in Children(item)) Visit(c, owner, childAnchor, rows, seen);
        }

        private List<string[]> Counters(IReadOnlyCollection<Item> members, IEnumerable<Item> direct)
        {
            var counters = new List<string[]>();
            var bugs = members.Where(i => i.Type == ItemType.Bug && IsOpen(i)).ToList();
            if (bugs.Count > 0)
                counters.Add([$"🐞 {bugs.Count} open {Plural(bugs.Count, "bug", "bugs")}: {BugSplit(bugs)}", "", "", ""]);
            var directList = direct.ToList();
            foreach (var (type, one, many) in new[] { (ItemType.Todo, "todo", "todos"), (ItemType.Task, "task", "tasks") })
            {
                var (done, total) = Count(directList.Where(i => i.Type == type));
                if (total > 0) counters.Add([$"{Emoji(type)} {total} {Plural(total, one, many)}", Bar(done, total), "", ""]);
            }
            return counters;
        }

        private void WorkTable(List<WorkRow> rows, List<string[]> counters)
        {
            if (rows.Count == 0 && counters.Count == 0) return;
            TableHead("Work", "Progress", "Due", "Notes");
            foreach (var r in rows)
            {
                var i = r.Item;
                var link = ItemLink(i);
                var work = $"{(r.Child ? "└ " : "")}{Emoji(i.Type)} {(IsOpen(i) ? link : $"~~{link}~~")}";
                var progress = "";
                if (i.Type != ItemType.Bug)
                {
                    var (done, total) = Count(Below(i));
                    progress = total == 0 ? "nothing planned" : Bar(done, total);
                }
                Row(work, progress, i.Due is { } d ? Date(d) : "", WorkNotes(r));
            }
            foreach (var c in counters) Row(c);
            Line();
        }

        private string WorkNotes(WorkRow r)
        {
            var i = r.Item;
            var parts = new List<string>();
            if (IsOpen(i))
            {
                if (i.Priority != Priority.Normal) parts.Add(i.Priority.ToWire());
                if (!string.IsNullOrEmpty(i.Effort)) parts.Add($"effort {GfmText.Escape(i.Effort)}");
                switch (i.State)
                {
                    case ItemState.InProgress: parts.Add("in progress"); break;
                    case ItemState.Review: parts.Add("review"); break;
                    case ItemState.Draft: parts.Add("draft"); break;
                }
                if (i.IsBlocked) parts.Add($"⛔ {GfmText.Escape(i.BlockedSummary)}");
                if (Overdue(i)) parts.Add("⚠ overdue");
                else if (Risk(i) is { AtRisk: true, ImpliedDeadline: { } needed }) parts.Add($"⚠ at risk: needed by {Date(needed)}");
            }
            parts.AddRange(Rollup(r.TasksOverdue, r.TasksAtRisk, r.TodosOverdue, r.TodosAtRisk));
            return string.Join(" · ", parts);
        }

        private static IEnumerable<string> Rollup(int tasksOverdue, int tasksAtRisk, int todosOverdue, int todosAtRisk)
        {
            if (tasksOverdue > 0) yield return $"{tasksOverdue} {Plural(tasksOverdue, "task", "tasks")} overdue";
            if (tasksAtRisk > 0) yield return $"{tasksAtRisk} {Plural(tasksAtRisk, "task", "tasks")} at risk";
            if (todosOverdue > 0) yield return $"{todosOverdue} {Plural(todosOverdue, "todo", "todos")} overdue";
            if (todosAtRisk > 0) yield return $"{todosAtRisk} {Plural(todosAtRisk, "todo", "todos")} at risk";
        }

